// Lists every fixed text the app can play from a recording, with its key and the exact Bengali
// to record (src/lib/audioKeys.ts). Re-run after changing any of those texts, so the recordings
// are redone for the lines that changed.
// Run: npx tsx scripts/audio-script.ts [--write]   (--write saves docs/audio-script.md)
import { writeFileSync } from 'node:fs'
import { AUDIO_KEY } from '@/lib/audioKeys'
import { CROP_IDS, CROPS } from '@/lib/crops'
import { RISK_VIEW, RISKS } from '@/lib/data'
import { QUESTIONS } from '@/lib/diagnosis/questions'
import { INTRO, speechOf } from '@/lib/guide'

type Line = { key: string; text: string; where: string }

const lines: Line[] = [
  ...RISKS.map((r) => ({ key: AUDIO_KEY.riskWord(r), text: RISK_VIEW[r].word, where: "Home's শুনুন: the risk word" })),
  ...RISKS.map((r) => ({ key: AUDIO_KEY.riskTitle(r), text: RISK_VIEW[r].title, where: "Home's শুনুন: the decision's title" })),
  ...CROP_IDS.flatMap((c) =>
    RISKS.map((r) => ({
      key: AUDIO_KEY.decision(c, r),
      text: CROPS[c].decision[r],
      where: `Home's শুনুন: ${CROPS[c].nameBn}'s decision (only when no danger day is ahead; that text names the day)`,
    })),
  ),
  ...INTRO.map((card, i) => ({ key: AUDIO_KEY.intro(i), text: speechOf(card), where: `First-run intro, card ${i + 1}` })),
  ...CROP_IDS.flatMap((c) => QUESTIONS[c].map((q) => ({ key: AUDIO_KEY.question(q.id), text: q.text, where: `${CROPS[c].nameBn} questions` }))),
]

const keys = new Set(lines.map((l) => l.key))
if (keys.size !== lines.length) throw new Error('Two texts share an audio key')

const md = `# Audio script

Recorded Bengali for the app's fixed texts. Generated by \`npx tsx scripts/audio-script.ts --write\` from the texts the app shows, so re-run it after changing any of them and re-record the lines that changed.

How to add a recording: save it as \`public/audio/<key>.mp3\` (mono, 64 kbps is plenty), read exactly the text below, at a calm pace. «শুনুন» plays the file when it is there and falls back to the phone's text-to-speech when it isn't, so recordings can be added one at a time. The place name, the weather numbers and a danger day's date are never recorded: they change, so the phone reads them.

${lines.length} lines.

| Key | Where | Read this |
|---|---|---|
${lines.map((l) => `| \`${l.key}\` | ${l.where} | ${l.text.replace(/\|/g, '\\|')} |`).join('\n')}
`

if (process.argv.includes('--write')) {
  writeFileSync('docs/audio-script.md', md)
  console.log(`Wrote docs/audio-script.md (${lines.length} lines)`)
} else {
  console.log(md)
}
